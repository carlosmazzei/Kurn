import Foundation
import Testing

struct FluidAudioModelLicensesTests {
    @Test func appBundleContainsCompleteOpenMDWAgreement() throws {
        let text = try bundledText()
        #expect(text.contains(Self.openMDWAgreement))
        #expect(text.contains("Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved."))
    }

    @Test func appBundleRetainsModelOriginsAndUpstreamNotices() throws {
        let text = try bundledText()
        let requiredNotices = [
            "nvidia/nemotron-labs-unified-asr-0.6b",
            "nvidia/NVIDIA-Nemotron-3.5-Transcribe-30B-A4B",
            "nvidia/Nemotron-3-Diarization",
            "ConwayResearch/Underdog-Bark-3.0",
            "ConwayResearch/Underdog-Bark-3.0-Clean",
            "FermionResearch/Phonon-2",
            "nvidia/parakeet-tdt-0.6b-v3",
            "moondream/parakeet-ultra",
            "Copyright 2026 Fermion Research",
            "BEGIN VERBATIM BARK 3.0 NOTICE",
            "END VERBATIM BARK 3.0 NOTICE",
            "BEGIN VERBATIM BARK 3.0 CLEAN NOTICE",
            "END VERBATIM BARK 3.0 CLEAN NOTICE",
            "BEGIN VERBATIM PHONON-2 NOTICE",
            "END VERBATIM PHONON-2 NOTICE",
            "CHiME-6",
            "SPGISpeech"
        ]
        for notice in requiredNotices {
            #expect(text.contains(notice))
        }
    }

    @Test func appBundleContainsCCBYLicenseThroughFinalSection() throws {
        let text = try bundledText()
        #expect(text.contains("Creative Commons Attribution 4.0 International Public License"))
        #expect(text.contains("Section 5 -- Disclaimer of Warranties and Limitation of Liability."))
        #expect(text.contains("Creative Commons may be contacted at creativecommons.org."))
        #expect(text.contains("END VERBATIM CC-BY-4.0 LICENSE FILE"))
        for section in 1...8 {
            #expect(text.contains("Section \(section) -- "))
        }
    }

    private func bundledText() throws -> String {
        let url = try #require(Bundle.main.url(forResource: "FluidAudioModelLicenses", withExtension: "txt"))
        return try String(contentsOf: url, encoding: .utf8)
